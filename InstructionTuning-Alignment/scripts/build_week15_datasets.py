def save_json(data, filepath):
    os.makedirs(os.path.dirname(filepath), exist_ok=True)
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

def build_instruction_from_emotion(sample):
    """用Prompt模板把情感分类任务转为指令格式"""
    return {
        "instruction": "请判断以下文本的情感倾向，并给出简短理由（正面/负面/中性）。",
        "input": sample["text"],
        "output": f"情感倾向：{sample['label']}。"
    }

def main():
    print("=" * 60)
    print("Week 15 指令微调 & DPO 数据集构造")
    print("=" * 60)

    # ---- SFT: 情感分类 + 医疗常识 ----
    sft_all = []
    for s in EMOTION_SAMPLES:
        sft_all.append(build_instruction_from_emotion(s))
    sft_all.extend(MEDICAL_QA_SAMPLES)
    random.shuffle(sft_all)

    # 划分 train/val (9:1)
    split = max(1, int(len(sft_all) * 0.9))
    sft_train = sft_all[:split]
    sft_val = sft_all[split:]

    sft_dir = "data/processed/sft_medical_emotion"
    save_json(sft_train, os.path.join(sft_dir, "train.json"))
    save_json(sft_val, os.path.join(sft_dir, "validation.json"))
    print(f"[SFT] 情感分类+医疗问答指令数据: train={len(sft_train)}, val={len(sft_val)}")
    print(f"      -> {sft_dir}/")

    # ---- DPO: 医疗偏好对 ----
    dpo_all = DPO_MEDICAL_PAIRS[:]
    random.shuffle(dpo_all)
    split = max(1, int(len(dpo_all) * 0.9))
    dpo_train = dpo_all[:split]
    dpo_val = dpo_all[split:]

    dpo_dir = "data/processed/dpo_medical_preference"
    save_json(dpo_train, os.path.join(dpo_dir, "train.json"))
    save_json(dpo_val, os.path.join(dpo_dir, "validation.json"))
    print(f"[DPO] 医疗好/坏回答偏好数据: train={len(dpo_train)}, val={len(dpo_val)}")
    print(f"      -> {dpo_dir}/")

    print("\n数据字段示例：")
    print(f"  SFT  keys: {list(sft_train[0].keys())}")
    print(f"  DPO  keys: {list(dpo_train[0].keys())}")

    print("\n" + "=" * 60)
    print("数据构造完成！下一步：用 TinyLlama + LoRA 跑 SFT → SFT+DPO 对比")
    print("=" * 60)

if __name__ == "__main__":
    main()
